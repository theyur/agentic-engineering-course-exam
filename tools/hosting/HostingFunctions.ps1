# Functions shared by provision.ps1 and teardown.ps1 (research R-03). Dot-source this file.
# Everything here runs without Azure or GitHub, so tools/hosting/selftest.ps1 tests it offline.
# Nothing here prints a value: secret values reach the Azure CLI only through files (Invoke-WithSecretFile).

# HP-014: the configured administrator stays visibly synthetic. Exactly one '@', a non-empty local part, no
# whitespace, and the domain exactly example.com (case-insensitive; subdomains are refused).
function Test-DemoAdministratorEmail {
    [CmdletBinding()]
    [OutputType([bool])]
    param([AllowNull()][AllowEmptyString()][string]$Email)

    if ([string]::IsNullOrWhiteSpace($Email) -or $Email -match '\s') { return $false }
    $parts = $Email.Split('@')
    if ($parts.Count -ne 2 -or $parts[0].Length -eq 0) { return $false }
    return $parts[1] -ieq 'example.com'
}

# Writes $Value (UTF-8, no BOM, no trailing newline) to a new file in the user's temporary folder, invokes
# $Action with the file's path and returns the action's output. The file is deleted in `finally`, so it is gone
# after a normal return and after the action throws. Callers pass the path to the Azure CLI as "@<path>", so the
# value is never a command-line argument. Also used for non-secret request bodies, for the same quoting reasons.
function Invoke-WithSecretFile {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$Value,
        [Parameter(Mandatory)][scriptblock]$Action
    )

    $path = Join-Path ([IO.Path]::GetTempPath()) ("ht-" + [IO.Path]::GetRandomFileName())
    try {
        $options = [IO.FileStreamOptions]::new()
        $options.Mode = [IO.FileMode]::CreateNew   # never reuse or follow an existing file
        $options.Access = [IO.FileAccess]::Write
        $options.Share = [IO.FileShare]::None
        if (-not $IsWindows) {
            # /tmp is shared on Linux and macOS: owner read/write only. (The Windows temp folder is per user.)
            $options.UnixCreateMode = [IO.UnixFileMode]::UserRead -bor [IO.UnixFileMode]::UserWrite
        }
        $stream = [IO.FileStream]::new($path, $options)
        try {
            $bytes = [Text.UTF8Encoding]::new($false).GetBytes($Value)
            $stream.Write($bytes, 0, $bytes.Length)
        }
        finally {
            $stream.Dispose()
        }
        & $Action $path
    }
    finally {
        if (Test-Path -LiteralPath $path) { Remove-Item -LiteralPath $path -Force }
    }
}

# True when the file exists and PowerShell's parser reports no error for it.
function Test-PowerShellParses {
    [CmdletBinding()]
    [OutputType([bool])]
    param([Parameter(Mandatory)][string]$Path)

    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $false }
    $fullPath = (Resolve-Path -LiteralPath $Path).ProviderPath
    $tokens = $null
    $errors = $null
    $null = [System.Management.Automation.Language.Parser]::ParseFile($fullPath, [ref]$tokens, [ref]$errors)
    return $errors.Count -eq 0
}

# The SQL server administrator password (research R-03): 32 letters and digits from RandomNumberGenerator,
# drawn again until it holds an upper-case letter, a lower-case letter and a digit (Azure SQL requires three of
# four character classes).
function New-SqlAdministratorPassword {
    [CmdletBinding()]
    [OutputType([string])]
    param()

    $alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
    do {
        $chars = [char[]]::new(32)
        for ($i = 0; $i -lt $chars.Length; $i++) {
            $chars[$i] = $alphabet[[System.Security.Cryptography.RandomNumberGenerator]::GetInt32($alphabet.Length)]
        }
        $password = [string]::new($chars)
    } while ($password -cnotmatch '[A-Z]' -or $password -cnotmatch '[a-z]' -or $password -notmatch '[0-9]')
    return $password
}

# The connection string `HabitTracker` (contracts/hosted-configuration.md): SQL authentication, encrypted.
# The password is generated by New-SqlAdministratorPassword (letters and digits), so no value needs quoting.
function New-SqlConnectionString {
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory)][string]$ServerFqdn,
        [Parameter(Mandatory)][string]$Database,
        [Parameter(Mandatory)][string]$User,
        [Parameter(Mandatory)][string]$Password
    )

    return "Server=tcp:$ServerFqdn,1433;Initial Catalog=$Database;Persist Security Info=False;" +
        "User ID=$User;Password=$Password;MultipleActiveResultSets=False;Encrypt=True;" +
        'TrustServerCertificate=False;Connection Timeout=30;'
}

# The bulk format of `az webapp config appsettings set --settings @<file>`: a JSON list of
# {"name", "value", "slotSetting"} (the shape `az webapp config appsettings list` prints).
function ConvertTo-AppSettingsJson {
    [CmdletBinding()]
    [OutputType([string])]
    param([Parameter(Mandatory)][System.Collections.IDictionary]$Settings)

    $list = [System.Collections.Generic.List[object]]::new()
    foreach ($key in $Settings.Keys) {
        $list.Add([ordered]@{ name = [string]$key; value = [string]$Settings[$key]; slotSetting = $false })
    }
    return ConvertTo-Json -InputObject $list.ToArray() -Compress -Depth 3
}

# The IPv4 addresses of a comma-separated list such as the web app's possibleOutboundIpAddresses, distinct and
# in order. SQL server firewall rules take IPv4 addresses only. Callers wrap the result in @().
function Get-IPv4AddressList {
    [CmdletBinding()]
    [OutputType([string[]])]
    param([AllowNull()][AllowEmptyString()][string]$List)

    $result = [System.Collections.Generic.List[string]]::new()
    if ([string]::IsNullOrWhiteSpace($List)) { return $result.ToArray() }
    foreach ($item in $List.Split(',')) {
        $candidate = $item.Trim()
        $address = $null
        if ([System.Net.IPAddress]::TryParse($candidate, [ref]$address) -and
            $address.AddressFamily -eq [System.Net.Sockets.AddressFamily]::InterNetwork -and
            $address.ToString() -eq $candidate -and -not $result.Contains($candidate)) {
            $result.Add($candidate)
        }
    }
    return $result.ToArray()
}

# Runs an external tool (az, gh) and returns its standard output; its error output goes to the console. A
# non-zero exit code throws. The message names the tool and its command words (the arguments before the first
# option) only, never an option value. No secret is ever an argument; this is defence in depth.
function Invoke-NativeTool {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$FilePath,
        [string[]]$ArgumentList = @()
    )

    $output = & $FilePath @ArgumentList
    $exitCode = $LASTEXITCODE
    if ($exitCode -ne 0) {
        $words = [System.Collections.Generic.List[string]]::new()
        foreach ($argument in $ArgumentList) {
            if ($argument.StartsWith('-')) { break }
            $words.Add($argument)
        }
        $command = (@([IO.Path]::GetFileNameWithoutExtension($FilePath)) + $words) -join ' '
        throw "$command failed with exit code $exitCode"
    }
    return $output
}
